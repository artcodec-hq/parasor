const SPECIAL_FILE_FOLDER_ICONS: Record<string, IconComponent> = {
  // Files like `.git/` would be folders, but in the registry above we treat
  // them as both: NAMED_FOLDER_ICONS handles the closed/opened pair.
};
void SPECIAL_FILE_FOLDER_ICONS;

export function getFileIconComponent(filename: string): IconComponent {
  const lower = filename.toLowerCase();
  const named = NAMED_FILE_ICONS[lower];
  if (named) return named;
  const dot = lower.lastIndexOf(".");
  if (dot < 0) return Document;
  const ext = lower.slice(dot + 1);
  return EXTENSION_ICONS[ext] ?? Document;
}

export function getFolderIconComponent(
  folderName: string,
  expanded: boolean,
): IconComponent {
  const named = NAMED_FOLDER_ICONS[folderName.toLowerCase()];
  if (named) return expanded ? named.opened : named.closed;
  return expanded ? FolderOpen : Folder;
}
