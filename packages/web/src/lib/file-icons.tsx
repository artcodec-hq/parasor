/*
 * File-tree icon registry. Wraps `@react-symbols/icons` (Symbols by Miguel
 * Solorio, ported to React by pheralb, MIT). Each entry is an SVG component
 * that renders the same colored icon the upstream Symbols icon set uses, so
 * the FileTree pane gets familiar language colors at a glance.
 *
 * Color-rich iconography is otherwise avoided UI-wide; this is a deliberate
 * exception scoped to the FileTree pane only -- language colors are one of
 * the most useful visual scans in a code-focused tool.
 */

